import { test, expect, register } from './fixtures';
const invoiceHeader = 'invoice_number,customer_name,issue_date,due_date,currency,total_amount\n';
const invoiceRow = 'UI-INV-1,"Synthetic, Studio",2026-10-01,2026-10-31,GBP,120.50\n';
const payments = 'transaction_date,description,amount,currency\n2026-10-10,UI transfer,120.50,GBP\n2026-10-10,UI transfer,120.50,GBP\n';
test('import samples, validate atomically, import invoices/payments and inspect lists/history', async ({ page }, testInfo) => {
  await register(page);
  await page.getByRole('link', { name: 'Import your invoices', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Import your records' })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download sample invoices CSV' }).click();
  expect((await download).suggestedFilename()).toBe('invoices.csv');
  await page.getByLabel('CSV file', { exact: true }).setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from(invoiceHeader + invoiceRow + 'UI-INV-2,Customer,2026-10-01,2026-10-31,GBP,-1\n') });
  // Keyboard submission uses the same native form and file picker control.
  await page.getByRole('button', { name: 'Import invoices', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Correct your file and try again' })).toBeVisible();
  await expect(page.getByText('No financial records from this file were inserted.', { exact: true })).toBeVisible();
  await expect(page.getByText(/Row 3 · total_amount/)).toBeVisible();
  await page.getByLabel('CSV file', { exact: true }).setInputFiles({ name: 'invoices.csv', mimeType: 'text/csv', buffer: Buffer.from(invoiceHeader + invoiceRow) });
  await page.getByRole('button', { name: 'Import invoices', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Import complete', exact: true })).toBeVisible();
  await expect(page.getByText('1 inserted · 0 duplicates skipped · 1 rows checked.')).toBeVisible();
  await page.getByRole('button', { name: 'Import invoices', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'This file was already imported' })).toBeVisible();
  await page.getByRole('button', { name: 'Next: import payments', exact: true }).click();
  await page.getByText('Add a named bank account', { exact: true }).click();
  await page.getByLabel('Bank account name', { exact: true }).fill('Synthetic current account');
  await page.getByRole('button', { name: 'Save bank account' }).click();
  await expect(page.getByLabel('Bank account', { exact: true })).not.toHaveValue('');
  await page.getByLabel('CSV file', { exact: true }).setInputFiles({ name: 'payments.csv', mimeType: 'text/csv', buffer: Buffer.from(payments) });
  await page.getByRole('button', { name: 'Import payments', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Import complete', exact: true })).toBeVisible();
  await expect(page.getByText(/2 incoming payments need duplicate review/)).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('import-summary.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'View imported payments', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'UI transfer', exact: true })).toHaveCount(2);
  await expect(page.getByRole('cell', { name: 'Possible duplicate — review required' })).toHaveCount(2);
  await page.getByRole('link', { name: 'Invoices', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'UI-INV-1', exact: true })).toBeVisible();
  await expect(page.getByRole('columnheader', { name: 'Outstanding', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: '£120.50', exact: true })).toHaveCount(2);
  await page.reload();
  await expect(page.getByRole('cell', { name: 'UI-INV-1', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Import', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'Rejected', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'View errors' }).click();
  await expect(page.getByRole('heading', { name: 'Import errors' })).toBeVisible();
});
