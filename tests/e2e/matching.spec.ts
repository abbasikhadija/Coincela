import { test, expect, register } from './fixtures';
import pg from 'pg';
test('review exact, ambiguous, unmatched and stale suggestions without allocating money', async ({ page }, testInfo) => {
  await register(page);
  const stored = await page.evaluate(() => JSON.parse(sessionStorage.getItem('coincela.session')!).token as string);
  const headers = { Authorization: `Bearer ${stored}` };
  const invoiceHeader = 'invoice_number,customer_name,issue_date,due_date,currency,total_amount\n';
  const invoiceCsv = invoiceHeader + 'REVIEW-1,Amber Studio,2026-10-01,2026-10-31,GBP,100.00\nREVIEW-2,Birch Consulting,2026-10-01,2026-10-31,GBP,100.00\n';
  expect((await page.request.post('http://127.0.0.1:3002/imports/invoices', { headers: { ...headers, 'Content-Type': 'text/csv' }, data: invoiceCsv })).status()).toBe(201);
  const bank = await page.request.post('http://127.0.0.1:3002/bank-accounts', { headers, data: { name: 'Matching browser bank' } });
  const bankId = (await bank.json()).account.id;
  const txHeader = 'transaction_date,description,amount,currency,payment_reference\n';
  const txCsv = txHeader + '2026-10-10,Exact UI payment,100.00,GBP,REVIEW-1\n2026-10-10,Ambiguous UI payment,100.00,GBP,\n2026-10-10,Unmatched UI payment,7.77,GBP,UNKNOWN\n';
  expect((await page.request.post('http://127.0.0.1:3002/imports/transactions', { headers: { ...headers, 'Content-Type': 'text/csv', 'X-Bank-Account-Id': bankId }, data: txCsv })).status()).toBe(201);
  await page.getByRole('link', { name: 'Review Payments', exact: true }).click();
  await page.getByRole('button', { name: /Exact UI payment/ }).click();
  await page.getByRole('button', { name: 'Generate suggestions', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Exact reference match', exact: true })).toBeVisible();
  await expect(page.getByText('The payment contains invoice reference REVIEW-1.', { exact: true })).toBeVisible();
  await expect(page.getByText('Exact reference match · Unconfirmed suggestion', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Confirm allocation', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Reject suggestion for REVIEW-1' }).click();
  await expect(page.getByText('Exact reference match · Rejected suggestion', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Exact reference match · Rejected suggestion', { exact: true })).toBeVisible();
  const newInvoice = invoiceHeader + 'NEW-REVIEW,Another Customer,2026-10-01,2026-10-31,GBP,999.00\n';
  expect((await page.request.post('http://127.0.0.1:3002/imports/invoices', { headers: { ...headers, 'Content-Type': 'text/csv' }, data: newInvoice })).status()).toBe(201);
  await page.getByRole('button', { name: 'Refresh payment', exact: true }).click();
  await expect(page.getByText(/These suggestions are out of date/)).toBeVisible();
  await expect(page.getByText('Exact reference match · Rejected suggestion', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Regenerate suggestions' }).click();
  await expect(page.getByText('Exact reference match · Unconfirmed suggestion', { exact: true })).toBeVisible();
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: 'Back to payments' }).click();
  await page.getByRole('button', { name: /Ambiguous UI payment/ }).click();
  await page.getByRole('button', { name: 'Generate suggestions', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Ambiguous', exact: true })).toBeVisible();
  await expect(page.getByText('Ambiguous · Unconfirmed suggestion', { exact: true })).toHaveCount(2);
  await expect(page.getByText(/Several invoices could match/)).toBeVisible();
  await expect(page.getByText(/Amount alone is weak evidence/)).toHaveCount(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('review-ambiguous.png'), fullPage: true });
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: 'Back to payments' }).click();
  await page.getByRole('button', { name: /Unmatched UI payment/ }).click();
  await page.getByRole('button', { name: 'Generate suggestions', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No match', exact: true })).toBeVisible();
  const client = new pg.Client({ connectionString: process.env.TEST_DATABASE_URL }); await client.connect();
  try {
    const result = await client.query('SELECT (SELECT count(*) FROM payment_allocations a JOIN bank_transactions t ON t.id=a.bank_transaction_id WHERE t.bank_account_id=$1)::int AS allocations', [bankId]);
    expect(result.rows[0].allocations).toBe(0);
  } finally { await client.end(); }
});
